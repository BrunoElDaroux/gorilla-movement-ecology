"""
generate_notebooks.py
=====================
Creates all 6 Jupyter notebook (.ipynb) files for the
Mountain Gorilla Movement Ecology project.

Run from the project root:
    python generate_notebooks.py
"""

import json
import os

NB_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "notebooks")
os.makedirs(NB_DIR, exist_ok=True)


def nb(cells):
    """Build minimal valid .ipynb dict."""
    return {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.9.0"},
        },
        "cells": cells,
    }


def md(src):
    return {"cell_type": "markdown", "metadata": {}, "source": src}


def code(src):
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": src,
    }


def save(name, cells):
    path = os.path.join(NB_DIR, name)
    with open(path, "w") as f:
        json.dump(nb(cells), f, indent=1)
    print(f"  Created: {name}")


